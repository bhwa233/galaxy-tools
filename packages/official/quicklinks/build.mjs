import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "vite";
const root = fileURLToPath(new URL("./", import.meta.url));
await build({
  configFile: false,
  publicDir: false,
  ssr: { noExternal: true },
  build: {
    target: "node24",
    ssr: path.join(root, "backend.ts"),
    outDir: root,
    emptyOutDir: false,
    minify: false,
    rolldownOptions: {
      external: (id) => id.startsWith("node:"),
      output: {
        entryFileNames: "backend.mjs",
        banner: "/* Generated by build.mjs; bundled trusted backend. */\n/* oxlint-disable */",
      },
    },
  },
});
